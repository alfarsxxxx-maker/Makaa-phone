/**
 * Recognized Business Intent for Grounded AI Assistant (Section 6).
 */
enum class AiBusinessIntent(val titleArabic: String) {
    SALES_TODAY("مبيعات اليوم"),
    SALES_WEEKLY("مبيعات الأسبوع"),
    SALES_MONTHLY("مبيعات هذا الشهر"),
    RECEIVABLES_WHO_OWES("مديونيات ومستحقات العملاء"),
    HIGHEST_DEBTOR("أكبر مديونية على عميل"),
    HIGHEST_EXPENSE("أعلى مصروف مسجل"),
    WEEK_OVER_WEEK_COMPARISON("مقارنة مبيعات الأسبوع الحالي بالسابق"),
    TOP_CUSTOMER("أعلى العملاء شراءً"),
    TOP_SELLING("الأصناف الأكثر مبيعًا"),
    TOP_PROFITABLE_PRODUCT("أعلى المنتجات ربحية"),
    LOW_STOCK("نواقص المخزون وإعادة الطلب"),
    CASH_AND_WALLETS("أرصدة الخزينة والمحافظ"),
    MONTHLY_EXPENSES("مصروفات الشهر"),
    PENDING_REVIEW_OPERATIONS("العمليات المعلقة وبانتظار المراجعة"),
    OVERDUE_MAINTENANCE("الصيانة المتأخرة والمستحقة"),
    PRODUCT_LOOKUP("استعلام عن صنف"),
    ACTION_PROPOSAL("اقتراح تنفيذ عملية"),
    GENERAL_QUERY("استفسار عام عن المتجر")
}

/**
 * Verified Grounded Facts retrieved directly from the Room database before AI explanation.
 */
data class GroundedFactSheet(
    val intent: AiBusinessIntent,
    val summaryDataArabic: String,
    val structuredMetrics: Map<String, String> = emptyMap(),
    val itemsSummary: List<String> = emptyList(),
    val citationSourceArabic: String = "المصدر: القيود الدفترية الرسمية لقاعدة البيانات المحلية",
    val retrievedAt: Long = System.currentTimeMillis()
)

/**
 * Proposed Operational Action generated by AI (Section 7).
 * Strictly requires explicit User Review and Confirmation before execution.
 */
enum class AiProposedActionType(
    val titleArabic: String,
    val requiredPermission: PermissionCode
) {
    CREATE_EXPENSE("تسجيل مصروف تشغيلي", PermissionCode.EXPENSE_CREATE),
    ADJUST_INVENTORY("تسوية مخزون", PermissionCode.INVENTORY_ADJUST),
    CHANGE_PRICE("تعديل سعر بيع", PermissionCode.PRICE_CHANGE),
    CREATE_SALE_DRAFT("إنشاء مسودة فاتورة بيع", PermissionCode.SALE_CREATE),
    CREATE_PURCHASE_DRAFT("إنشاء مسودة شراء للأصناف الناقصة", PermissionCode.PURCHASE_CREATE),
    RECORD_MAINTENANCE_UPDATE("تحديث حالة صيانة", PermissionCode.MAINTENANCE_MANAGE)
}

enum class AiActionStatus {
    PENDING_REVIEW,
    CONFIRMED_AND_EXECUTED,
    REJECTED
}

data class AiActionProposal(
    val proposalId: String = IdGenerator.newPrefixedId("AIACT"),
    val actionType: AiProposedActionType,
    val titleArabic: String,
    val descriptionArabic: String,
    val parameters: Map<String, String>,
    val status: AiActionStatus = AiActionStatus.PENDING_REVIEW,
    val executedTransactionId: String? = null,
    val createdAt: Long = System.currentTimeMillis()
)

/**
 * Final Response delivered to the User.
 */
data class AiAssistantResponse(
    val userQuestion: String,
    val detectedIntent: AiBusinessIntent,
    val factualResultArabic: String,
    val groundedFacts: GroundedFactSheet,
    val proposedAction: AiActionProposal? = null,
    val isLlmSynthesized: Boolean = false,
    val responseTimestamp: Long = System.currentTimeMillis()
)

/**
 * Result of Product Vision Recognition (Section 8).
 */
data class ProductVisionCandidate(
    val productId: String,
    val productNameArabic: String,
    val sku: String,
    val barcode: String?,
    val currentStockQty: Int,
    val sellingPriceMinor: Long,
    val confidenceScorePercent: Int,
    val matchReasonArabic: String
)

data class ProductVisionResult(
    val matchedProducts: List<ProductVisionCandidate>,
    val isReliableMatch: Boolean,
    val statusMessageArabic: String
)
